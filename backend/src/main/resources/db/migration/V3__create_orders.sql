-- "order" is a reserved word in SQL, hence customer_order.
CREATE TABLE customer_order (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The Keycloak login name of the customer who placed it.
    customer_username VARCHAR(255)   NOT NULL,
    status            VARCHAR(20)    NOT NULL,
    total             NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    created_at        TIMESTAMPTZ    NOT NULL,
    updated_at        TIMESTAMPTZ    NOT NULL
);

CREATE INDEX customer_order_customer_idx ON customer_order (customer_username);
CREATE INDEX customer_order_status_idx ON customer_order (status);

CREATE TABLE order_line (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES customer_order (id),
    product_id   BIGINT         NOT NULL REFERENCES product (id),
    -- Name and price are copied at the moment of ordering, so a later change to the
    -- product does not rewrite what the customer agreed to.
    product_name VARCHAR(255)   NOT NULL,
    unit_price   NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    quantity     INTEGER        NOT NULL CHECK (quantity > 0)
);

CREATE INDEX order_line_order_idx ON order_line (order_id);
